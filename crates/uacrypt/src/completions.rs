//! `uacrypt completions <shell>` (T-264, `docs/DECISIONS.md` D-257): static tab-completion scripts
//! for bash, zsh, fish and PowerShell, generated from [`super::COMMANDS`] - the same table the
//! parsers scan with - so a script offers exactly the flags a command accepts, minus the hidden
//! ones. Completing never runs `uacrypt`. Every word is `[A-Za-z0-9-]` (a unit test), so no shell
//! needs quoting beyond the plain single quotes used here.

use super::{
    is_help_flag, print_command_help, unknown_subcommand, write_stdout, CliError, COMMANDS, SHELLS,
};
use core::fmt::Write as _;

/// Value flags that take a number, not a path: completed with nothing rather than file names.
const NUMBER_FLAGS: &[&str] = &["--iterations"];

/// What one top-level word completes to after it.
struct Entry {
    name: &'static str,
    /// Offered right after `name`, alone (with `--help`).
    subs: Vec<&'static str>,
    /// Offered from the first flag position on: the visible flags, then `--help`.
    flags: Vec<&'static str>,
    /// Visible value flags whose value is a file name.
    files: Vec<&'static str>,
    /// Visible value flags with a fixed set of values.
    choices: Vec<(&'static str, &'static [&'static str])>,
}

fn entries() -> Vec<Entry> {
    let mut out: Vec<Entry> = COMMANDS
        .iter()
        .map(|c| {
            let visible: Vec<&str> = c.flags.visible().collect();
            let choices: Vec<(&str, &[&str])> = c
                .flags
                .choices
                .iter()
                .copied()
                .filter(|(flag, _)| visible.contains(flag))
                .collect();
            let files = c
                .flags
                .values
                .iter()
                .copied()
                .filter(|f| visible.contains(f))
                .filter(|f| !NUMBER_FLAGS.contains(f) && !choices.iter().any(|(c, _)| c == f))
                .collect();
            Entry {
                name: c.name,
                subs: c.subcommands.to_vec(),
                flags: visible.into_iter().chain(["--help"]).collect(),
                files,
                choices,
            }
        })
        .collect();
    out.push(Entry {
        name: "help",
        subs: COMMANDS.iter().map(|c| c.name).collect(),
        flags: Vec::new(),
        files: Vec::new(),
        choices: Vec::new(),
    });
    out
}

/// The words offered right after `uacrypt`.
fn top_words() -> Vec<&'static str> {
    COMMANDS
        .iter()
        .map(|c| c.name)
        .chain(["help", "--help", "-h", "--version", "-V"])
        .collect()
}

/// `uacrypt completions <shell>`: prints the script, or a usage error.
///
/// # Errors
///
/// [`CliError::MissingSubcommand`] without a shell, an unknown-command error (with a suggestion)
/// for another word, [`CliError::UnexpectedArgument`] for anything after the shell, and
/// [`CliError::Io`] if stdout fails.
pub(crate) fn run_completions_command(rest: &[String]) -> Result<(), CliError> {
    if rest.iter().any(|a| is_help_flag(a)) {
        print_command_help("completions");
        return Ok(());
    }
    let shell = match rest {
        [] => return Err(CliError::MissingSubcommand("bash|zsh|fish|powershell")),
        [shell] => shell,
        [_, extra, ..] => return Err(CliError::UnexpectedArgument(extra.clone())),
    };
    let text = script(shell).ok_or_else(|| unknown_subcommand("completions", shell, SHELLS))?;
    write_stdout(&text)
}

/// The script for `shell`, or `None` for a shell not in [`SHELLS`].
pub(crate) fn script(shell: &str) -> Option<String> {
    match shell {
        "bash" => Some(bash()),
        "zsh" => Some(zsh()),
        "fish" => Some(fish()),
        "powershell" => Some(powershell()),
        _ => None,
    }
}

fn header(comment: &str) -> String {
    format!(
        "{comment} uacrypt {} tab completion, generated by `uacrypt completions` - regenerate it after \
         upgrading uacrypt.\n",
        env!("CARGO_PKG_VERSION")
    )
}

fn bash() -> String {
    let mut s = header("#");
    s.push_str(
        "_uacrypt_words() {
    local w
    COMPREPLY=()
    while IFS= read -r w; do COMPREPLY+=(\"$w\"); done < <(compgen -W \"$1\" -- \"$cur\")
}

_uacrypt_files() {
    local w
    COMPREPLY=()
    compopt -o filenames 2>/dev/null
    while IFS= read -r w; do COMPREPLY+=(\"$w\"); done < <(compgen -f -- \"$cur\")
}

_uacrypt() {
    local cur=\"${COMP_WORDS[COMP_CWORD]}\" prev=\"\"
    [ \"$COMP_CWORD\" -gt 0 ] && prev=\"${COMP_WORDS[COMP_CWORD-1]}\"
",
    );
    let _ = writeln!(
        s,
        "    if [ \"$COMP_CWORD\" -le 1 ]; then _uacrypt_words '{}'; return; fi",
        top_words().join(" ")
    );
    s.push_str("    local subs='' flags='' files=''\n    case \"${COMP_WORDS[1]}\" in\n");
    for e in entries() {
        let _ = writeln!(
            s,
            "        {}) subs='{}'; flags='{}'; files='{}' ;;",
            e.name,
            e.subs.join(" "),
            e.flags.join(" "),
            e.files.join(" ")
        );
    }
    s.push_str(
        "        *) return ;;
    esac
    if [ -n \"$subs\" ] && [ \"$COMP_CWORD\" -eq 2 ]; then _uacrypt_words \"$subs --help\"; return; fi
    case \"${COMP_WORDS[1]} $prev\" in
",
    );
    for e in entries() {
        for (flag, values) in &e.choices {
            let _ = writeln!(
                s,
                "        '{} {flag}') _uacrypt_words '{}'; return ;;",
                e.name,
                values.join(" ")
            );
        }
    }
    let _ = write!(
        s,
        "    esac
    case \"$prev\" in
        {}) COMPREPLY=(); return ;;
    esac
    case \" $files \" in
        *\" $prev \"*) _uacrypt_files; return ;;
    esac
    _uacrypt_words \"$flags\"
}}

complete -F _uacrypt uacrypt uacrypt.exe
",
        NUMBER_FLAGS.join("|")
    );
    s
}

fn zsh() -> String {
    let mut s = String::from("#compdef uacrypt uacrypt.exe\n");
    s.push_str(&header("#"));
    s.push_str(
        "_uacrypt() {
    local cmd=${words[2]} prev=${words[CURRENT-1]}
    local -a subs flags files
",
    );
    let _ = writeln!(
        s,
        "    if (( CURRENT <= 2 )); then compadd -- {}; return; fi",
        top_words().join(" ")
    );
    s.push_str("    case $cmd in\n");
    for e in entries() {
        let _ = writeln!(
            s,
            "        {}) subs=({}); flags=({}); files=({}) ;;",
            e.name,
            e.subs.join(" "),
            e.flags.join(" "),
            e.files.join(" ")
        );
    }
    s.push_str(
        "        *) return 1 ;;
    esac
    if (( ${#subs} && CURRENT == 3 )); then compadd -- $subs --help; return; fi
    case \"$cmd $prev\" in
",
    );
    for e in entries() {
        for (flag, values) in &e.choices {
            let _ = writeln!(
                s,
                "        '{} {flag}') compadd -- {}; return ;;",
                e.name,
                values.join(" ")
            );
        }
    }
    let _ = write!(
        s,
        "    esac
    case $prev in
        {}) return ;;
    esac
    if (( ${{files[(Ie)$prev]}} )); then _files; return; fi
    compadd -- $flags
}}

if [ \"$funcstack[1]\" = \"_uacrypt\" ]; then
    _uacrypt \"$@\"
else
    compdef _uacrypt uacrypt uacrypt.exe
fi
",
        NUMBER_FLAGS.join("|")
    );
    s
}

fn fish() -> String {
    let mut s = header("#");
    s.push_str(
        "function __uacrypt_top
    test (count (commandline -opc)) -eq 1
end
function __uacrypt_sub_slot
    set -l t (commandline -opc)
    test (count $t) -eq 2; and test \"$t[2]\" = \"$argv[1]\"
end
function __uacrypt_flag_slot
    set -l t (commandline -opc)
    test (count $t) -ge $argv[2]; and test \"$t[2]\" = \"$argv[1]\"
end
complete -c uacrypt -f
",
    );
    let names: Vec<&str> = COMMANDS.iter().map(|c| c.name).chain(["help"]).collect();
    let _ = writeln!(
        s,
        "complete -c uacrypt -n __uacrypt_top -a '{}'",
        names.join(" ")
    );
    s.push_str("complete -c uacrypt -n __uacrypt_top -s h -l help\n");
    s.push_str("complete -c uacrypt -n __uacrypt_top -s V -l version\n");
    for e in entries() {
        if !e.subs.is_empty() {
            let _ = writeln!(
                s,
                "complete -c uacrypt -n '__uacrypt_sub_slot {}' -a '{}'",
                e.name,
                e.subs.join(" ")
            );
        }
        // Flags start right after the command, or after its subcommand.
        let first = if e.subs.is_empty() { 2 } else { 3 };
        for flag in &e.flags {
            let long = &flag[2..];
            let kind = if e.files.contains(flag) {
                " -r -F".to_string()
            } else if let Some((_, values)) = e.choices.iter().find(|(f, _)| f == flag) {
                format!(" -x -a '{}'", values.join(" "))
            } else if NUMBER_FLAGS.contains(flag) {
                " -x".to_string()
            } else {
                String::new()
            };
            let _ = writeln!(
                s,
                "complete -c uacrypt -n '__uacrypt_flag_slot {} {first}' -l {long}{kind}",
                e.name
            );
        }
    }
    s
}

fn ps_list(words: &[&str]) -> String {
    let quoted: Vec<String> = words.iter().map(|w| format!("'{w}'")).collect();
    format!("@({})", quoted.join(", "))
}

fn powershell() -> String {
    let mut s = header("#");
    s.push_str(
        "Register-ArgumentCompleter -Native -CommandName 'uacrypt', 'uacrypt.exe' -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
",
    );
    let _ = writeln!(s, "    $top = {}", ps_list(&top_words()));
    let all = entries();
    let table = |pick: &dyn Fn(&Entry) -> Vec<&'static str>| -> String {
        let rows: Vec<String> = all
            .iter()
            .filter(|e| !pick(e).is_empty())
            .map(|e| format!("        '{}' = {}", e.name, ps_list(&pick(e))))
            .collect();
        format!("@{{\n{}\n    }}", rows.join("\n"))
    };
    let _ = writeln!(s, "    $subs = {}", table(&|e| e.subs.clone()));
    let _ = writeln!(s, "    $flags = {}", table(&|e| e.flags.clone()));
    let _ = writeln!(s, "    $files = {}", table(&|e| e.files.clone()));
    let choice_rows: Vec<String> = all
        .iter()
        .flat_map(|e| {
            e.choices.iter().map(move |(flag, values)| {
                format!("        '{} {flag}' = {}", e.name, ps_list(values))
            })
        })
        .collect();
    let _ = writeln!(s, "    $choices = @{{\n{}\n    }}", choice_rows.join("\n"));
    let _ = writeln!(s, "    $numbers = {}", ps_list(NUMBER_FLAGS));
    s.push_str(
        "    $before = @($commandAst.CommandElements |
        Where-Object { $_.Extent.EndOffset -lt $cursorPosition } |
        ForEach-Object { $_.Extent.Text })
    $pos = $before.Count
    $candidates = @()
    if ($pos -le 1) {
        $candidates = $top
    } else {
        $cmd = $before[1]
        $prev = $before[$pos - 1]
        if ($subs.ContainsKey($cmd) -and $pos -eq 2) {
            $candidates = $subs[$cmd] + @('--help')
        } elseif ($choices.ContainsKey(\"$cmd $prev\")) {
            $candidates = $choices[\"$cmd $prev\"]
        } elseif ($numbers -contains $prev) {
            return
        } elseif ($files.ContainsKey($cmd) -and $files[$cmd] -contains $prev) {
            return
        } elseif ($flags.ContainsKey($cmd)) {
            $candidates = $flags[$cmd]
        }
    }
    $candidates | Where-Object { $_ -like \"$wordToComplete*\" } | ForEach-Object {
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }
}
",
    );
    s
}

#[cfg(test)]
mod tests {
    use super::{entries, script, top_words, NUMBER_FLAGS};
    use crate::{COMMANDS, SHELLS};

    fn plain(word: &str) -> bool {
        !word.is_empty() && word.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-')
    }

    #[test]
    fn every_word_needs_no_quoting_in_any_shell() {
        for e in entries() {
            let words = e
                .subs
                .iter()
                .chain(&e.flags)
                .chain(e.choices.iter().flat_map(|(_, v)| v.iter()));
            for word in words.chain([&e.name]) {
                assert!(plain(word), "{}: {word:?}", e.name);
            }
        }
        assert!(top_words().iter().all(|w| plain(w)));
    }

    #[test]
    fn entries_hold_exactly_the_visible_flags_and_never_a_hidden_one() {
        for (c, e) in COMMANDS.iter().zip(entries()) {
            assert_eq!(c.name, e.name);
            let visible: Vec<&str> = c.flags.visible().chain(["--help"]).collect();
            assert_eq!(e.flags, visible, "{}", c.name);
            for hidden in c.flags.hidden {
                assert!(!e.flags.contains(hidden), "{}: {hidden}", c.name);
                assert!(!e.files.contains(hidden), "{}: {hidden}", c.name);
                assert!(!e.choices.iter().any(|(f, _)| f == hidden), "{}", c.name);
            }
            for file in &e.files {
                assert!(c.flags.values.contains(file) && !NUMBER_FLAGS.contains(file));
            }
        }
        let help = entries().pop().expect("help entry");
        assert_eq!(help.name, "help");
        assert_eq!(
            help.subs,
            COMMANDS.iter().map(|c| c.name).collect::<Vec<_>>()
        );
    }

    #[test]
    fn every_script_names_every_command_subcommand_flag_and_choice() {
        for shell in SHELLS {
            let text = script(shell).expect(shell);
            for e in entries() {
                assert!(text.contains(e.name), "{shell}: {}", e.name);
                for word in e.subs.iter().chain(&e.flags) {
                    let word = word.trim_start_matches('-');
                    assert!(text.contains(word), "{shell}: {} {word}", e.name);
                }
                for (_, values) in &e.choices {
                    assert!(
                        text.contains(&values.join(" ")) || text.contains(&values.join("', '")),
                        "{shell}: {}",
                        e.name
                    );
                }
            }
            assert!(text.contains(env!("CARGO_PKG_VERSION")), "{shell}");
        }
    }

    #[test]
    fn an_unknown_shell_has_no_script() {
        assert!(script("tcsh").is_none());
        assert!(script("").is_none());
        assert!(script("Bash").is_none());
    }
}
