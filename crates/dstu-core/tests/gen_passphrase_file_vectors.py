"""Writes tests/vectors/pwhash/passphrase_file.json from files sealed by a released uacrypt (T-269).

Usage: python -I gen_passphrase_file_vectors.py <path to uacrypt 0.6.0> <output json>

The valid cases are what `uacrypt encrypt --passphrase-file` 0.6.0 wrote (D-219), so they pin the
format the core codec must keep reading and writing; they are compat vectors, not an oracle (the
header is this project's own format). The negative cases are derived from valid_short by editing
bytes; only the ones marked so in `argon2` need an Argon2 run to be refused.
"""
import json
import os
import subprocess
import sys
import tempfile

HEADER_BYTES = 28
CHUNK_BYTES = 8192


def plaintext(n):
    return bytes((i * 31 + 7) % 256 for i in range(n))


def seal(exe, workdir, name, passphrase, data):
    pw_path = os.path.join(workdir, name + ".pw")
    in_path = os.path.join(workdir, name + ".in")
    out_path = os.path.join(workdir, name + ".uac")
    back_path = os.path.join(workdir, name + ".back")
    with open(pw_path, "wb") as f:
        f.write(passphrase)
    with open(in_path, "wb") as f:
        f.write(data)
    subprocess.run([exe, "encrypt", "--passphrase-file", pw_path, "--in", in_path, "--out", out_path],
                   check=True, capture_output=True)
    subprocess.run([exe, "decrypt", "--passphrase-file", pw_path, "--in", out_path, "--out", back_path],
                   check=True, capture_output=True)
    with open(back_path, "rb") as f:
        if f.read() != data:
            sys.exit(f"{name}: uacrypt round trip mismatch")
    with open(out_path, "rb") as f:
        return f.read()


def case(name, expect, passphrase, data, sealed, argon2):
    return {
        "name": name,
        "expect": expect,
        "argon2": argon2,
        "passphrase_hex": passphrase.hex(),
        "plaintext_len": len(data),
        "sealed_hex": sealed.hex(),
    }


def main():
    exe, out = sys.argv[1], sys.argv[2]
    version = subprocess.run([exe, "--version"], check=True, capture_output=True, text=True).stdout.strip()
    ascii_pw = b"correct horse battery staple"
    uk_pw = "пароль з пробілом ".encode("utf-8")
    cases = []
    with tempfile.TemporaryDirectory() as workdir:
        short_data = plaintext(20)
        short = seal(exe, workdir, "short", uk_pw, short_data)
        two_data = plaintext(CHUNK_BYTES + 5)
        two = seal(exe, workdir, "two", ascii_pw, two_data)
    cases.append(case("valid_short", "ok", uk_pw, short_data, short, True))
    cases.append(case("valid_two_records", "ok", ascii_pw, two_data, two, True))
    cases.append(case("wrong_passphrase", "invalid_ciphertext", ascii_pw, short_data, short, True))
    tampered = bytearray(short)
    tampered[-1] ^= 0x01
    cases.append(case("tampered_record", "invalid_ciphertext", uk_pw, short_data, bytes(tampered), True))

    def edit(index, value):
        b = bytearray(short)
        b[index] = value
        return bytes(b)

    sensitive = bytearray(short)
    sensitive[3:7] = (1_048_576).to_bytes(4, "little")
    sensitive[7:11] = (4).to_bytes(4, "little")
    cases.append(case("not_passphrase_file", "not_passphrase_file", uk_pw, short_data, edit(0, 0x02), False))
    cases.append(case("container_version_2", "unsupported_format", uk_pw, short_data, edit(1, 0x02), False))
    cases.append(case("kdf_2", "unsupported_format", uk_pw, short_data, edit(2, 0x02), False))
    cases.append(case("costs_sensitive", "unsupported_params", uk_pw, short_data, bytes(sensitive), False))
    cases.append(case("parallelism_4", "unsupported_params", uk_pw, short_data, edit(11, 0x04), False))
    cases.append(case("header_only", "truncated", uk_pw, short_data, short[:HEADER_BYTES - 1], False))
    doc = {
        "source": ("Compat vectors, not an oracle (T-269, D-219): valid cases written by `" + version +
                   "` encrypt --passphrase-file (release asset, SHA256SUMS-checked) and round-tripped by it;"
                   " negatives edit valid_short's bytes. Generated by crates/dstu-core/tests/"
                   "gen_passphrase_file_vectors.py. The 28-byte header is this project's own format, so no"
                   " independent oracle exists; derive_key's own oracle is libsodium (derive_key.json)."
                   " Plaintext of a valid case is (i*31+7) mod 256 of plaintext_len bytes (negatives keep"
                   " valid_short's length). expect: ok | invalid_ciphertext |"
                   " not_passphrase_file | unsupported_format | unsupported_params | truncated. argon2:"
                   " whether refusing or opening the case runs Argon2 (256 MiB, t=3) - false cases are refused"
                   " from the header alone."),
        "header_bytes": HEADER_BYTES,
        "cases": cases,
    }
    # One case per line, like box/v3.json, so a reader can scan it line by line.
    head = {k: v for k, v in doc.items() if k != "cases"}
    lines = ["{"] + [f"  {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}," for k, v in head.items()]
    lines.append('  "cases": [')
    lines += [f"    {json.dumps(c, ensure_ascii=False)}," for c in doc["cases"]]
    lines[-1] = lines[-1].rstrip(",")
    lines += ["  ]", "}"]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
